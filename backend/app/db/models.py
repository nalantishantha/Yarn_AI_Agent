    Yarn_4 = Column('Yarn 4', Integer, ForeignKey('yarn_and_supplier_database.Material_No'))
    Yarn_5 = Column('Yarn 5', Integer, ForeignKey('yarn_and_supplier_database.Material_No'))
    Yarn_6 = Column('Yarn 6', Integer, ForeignKey('yarn_and_supplier_database.Material_No'))
